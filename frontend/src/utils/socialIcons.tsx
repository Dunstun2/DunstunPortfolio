/**
 * Get the SVG icon for a platform name.
 * Matches case-insensitively and handles common variants.
 */
export function getSocialIcon(platformName: string): React.ReactNode {
  if (!platformName) return fallbackIcon;
  const key = platformName.toLowerCase().trim();
  
  // Direct match
  if (icons[key]) return icons[key];
  
  // Partial / alias matching
  if (key.includes('github')) return icons.github;
  if (key.includes('linkedin')) return icons.linkedin;
  if (key.includes('twitter') || key === 'x') return icons['twitter / x'];
  if (key.includes('instagram')) return icons.instagram;
  if (key.includes('facebook')) return icons.facebook;
  if (key.includes('youtube')) return icons.youtube;
  if (key.includes('dribbble')) return icons.dribbble;
  if (key.includes('behance')) return icons.behance;
  if (key.includes('medium')) return icons.medium;
  if (key.includes('stack')) return icons['stack overflow'];
  if (key.includes('discord')) return icons.discord;
  if (key.includes('telegram')) return icons.telegram;
  if (key.includes('whatsapp')) return icons.whatsapp;
  if (key.includes('tiktok') || key.includes('ticktok')) return icons.tiktok;

  return fallbackIcon;
}

